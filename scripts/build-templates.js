#!/usr/bin/env node
// Bundles public/ into src/ui-templates-generated.ts (Workers can't read files at runtime)
const fs = require('fs');
const path = require('path');

const pub = (p) => fs.readFileSync(path.join(__dirname, '../public', p), 'utf8');
const styles = pub('css/styles.css');
const page = (name) => pub(`html/${name}.html`)
  .replace('/*{{STYLES}}*/', () => styles)
  .replace(/<!--\{\{include:([\w-]+)\}\}-->\n?/g, (_, part) => pub(`html/_${part}.html`));

const templates = {
  oauthSetup: page('oauth-setup'),
  success: page('success'),
  error: page('error'),
  consent: page('consent'),
  favicon: pub('favicon.svg'),
};

const body = Object.entries(templates)
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  .join('\n');
fs.writeFileSync(
  path.join(__dirname, '../src/ui-templates-generated.ts'),
  `// Auto-generated by scripts/build-templates.js - DO NOT EDIT\n\nexport const templates = {\n${body}\n};\n`
);
console.log('Templates built to src/ui-templates-generated.ts');
